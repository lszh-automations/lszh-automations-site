// OFFLINE cryptographic identity-verification fixture. NO HTTP listener,
// Cloud IAM grant, token minting, remote Google/JWKS request or live permission.
// This is NOT a production Google ID token verifier. The RSA public key is
// trusted TEST CONFIG supplied by the internal test harness, never by Make.
// Production must use Cloud Run IAM verified invokers and a separately approved
// identity-federation capability and key-rotation design.
import {createPublicKey,verify} from 'node:crypto';
import {resolveAndReserveSyntheticMakeLocalEmulator} from './syntheticSourceIndex.mjs';

const AUD='https://lszh-reservation.demo.invalid';
const ISS='https://accounts.google.com';
const EMAIL='make-caller@demo-lszh-automations.iam.gserviceaccount.com';
const SUB='123456789012345678901';
const B64=/^[A-Za-z0-9_-]+$/;
const ID=/^[A-Za-z0-9_-]{8,80}$/;
const JWT=/^[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/;
const MAX_TOKEN_BYTES=8192;
const CLOCK_SKEW_SECONDS=30;
const MAX_LIFETIME_SECONDS=3600;

const noGo=(reason='caller_identity_unverified')=>({
  status:'NO_GO',reason,stopBeforeModule:5,manualReviewRequired:true,
  canCreateGoogleDoc:false,canExportPdf:false,canUpload:false,
  canWriteFirestore:false,canWriteAirtable:false,canSendEmail:false
});
function decodeJson(part){
  if(!B64.test(part) || part.length>6000)throw Error('invalid_jwt');
  const buf=Buffer.from(part,'base64url');
  if(buf.toString('base64url')!==part)throw Error('invalid_jwt');
  const value=JSON.parse(buf.toString('utf8'));
  if(!value || typeof value!=='object'||Array.isArray(value))
    throw Error('invalid_jwt');
  return value;
}
function exact(obj,keys){
  return Object.keys(obj).sort().join('|')===keys.slice().sort().join('|');
}

/** Caller is a strictly synthetic Google-shaped RSA-signed JWT generated by
 * offline tests only. trustedPublicJwk and trustedKid must be INTERNAL
 * server configuration, not supplied by a Make request.
 * Any successful result still forbids document creation and data delivery.
 */
export function verifySyntheticMakeCallerOffline({identityToken,trustedPublicJwk,
  trustedKid,now}={}){
  try{
    if(typeof identityToken!=='string'||identityToken.length>MAX_TOKEN_BYTES ||
       !JWT.test(identityToken)||!ID.test(trustedKid||'')||
       !(now instanceof Date)||!Number.isFinite(now.getTime()) ||
       !trustedPublicJwk || trustedPublicJwk.kty!=='RSA'||
       typeof trustedPublicJwk.n!=='string'||typeof trustedPublicJwk.e!=='string')
      return noGo();

    const parts=identityToken.split('.');
    const header=decodeJson(parts[0]),claims=decodeJson(parts[1]);
    if(!exact(header,['alg','kid','typ']) ||
       header.alg!=='RS256'||header.typ!=='JWT'||
       header.kid!==trustedKid) return noGo();

    // Do not trust jku/jwk/x5u URLs or an algorithm from the JWT header.
    const pub=createPublicKey({
      key:{kty:'RSA',n:trustedPublicJwk.n,e:trustedPublicJwk.e},
      format:'jwk'
    });
    const sig=Buffer.from(parts[2],'base64url');
    if(sig.toString('base64url')!==parts[2]||
       !verify('RSA-SHA256',Buffer.from(parts[0]+'.'+parts[1]),pub,sig))
      return noGo();

    const nowSecs=Math.floor(now.getTime()/1000);
    if(claims.iss!==ISS || claims.aud!==AUD ||
       claims.sub!==SUB || claims.email!==EMAIL ||
       claims.email_verified!==true ||
       !Number.isSafeInteger(claims.iat)||
       !Number.isSafeInteger(claims.exp)||
       claims.exp<=claims.iat ||
       claims.exp-claims.iat>MAX_LIFETIME_SECONDS ||
       claims.iat>nowSecs+CLOCK_SKEW_SECONDS ||
       claims.exp<=nowSecs-CLOCK_SKEW_SECONDS ||
       (claims.nbf!==undefined &&
         (!Number.isSafeInteger(claims.nbf)||
           claims.nbf>nowSecs+CLOCK_SKEW_SECONDS)))
      return noGo();

    return {
      status:'VERIFIED_OFFLINE_FIXTURE_ONLY',
      caller:'SYNTHETIC_DEMO_MAKE_CALLER',
      stopBeforeModule:5,manualReviewRequired:true,
      canCreateGoogleDoc:false,canExportPdf:false,canUpload:false,
      canWriteFirestore:false,canWriteAirtable:false,canSendEmail:false
    };
  }catch{
    // No raw token, kid, claim, signature or provider diagnostics to output.
    return noGo();
  }
}

/** Authentication gate of the local-emulator lookup, never a public endpoint.
 * A fake token or missing internal trust configuration returns NO_GO WITHOUT
 * touching Firestore. Even a valid fixture only reaches an existing
 * local-emulator-only review lock, which ALWAYS returns a STOP result.
 */
export async function authenticatedSyntheticMakeReviewLocalEmulator(db,{
  identityToken,trustedPublicJwk,trustedKid,payload,now
}={}){
  const decision=verifySyntheticMakeCallerOffline({
    identityToken,trustedPublicJwk,trustedKid,now
  });
  if(decision.status!=='VERIFIED_OFFLINE_FIXTURE_ONLY')
    return decision;
  return resolveAndReserveSyntheticMakeLocalEmulator(db,payload,now);
}
export const SYNTHETIC_AUTH_AUDIENCE=AUD;
